#!/usr/bin/env python3
"""OMNI_INPROC_NET_WRAPS_V1 (2026-11-24): link stage1/src-title/omni_inproc_net_wraps.c into the TITLE so WebKit's
NetworkProcess (curl) can run inside the title: non-blocking sockets via SO_NBIO (--wrap=fcntl) and getaddrinfo on
Sony's resolver (libSceNet). See the .c file for the console facts.

History:
  R2: the title links libSceNet like the engine child (-lSceNet; it cannot load modules at runtime). The recipe's import
      gate allows exactly the resolver imports (+ sceNetInit, R3).
  R4/R5 (console gin31, then a link error): the RADV link recipe (tools/radv-link.sh ~line 86) binds getaddrinfo and
      freeaddrinfo to the SDK stubs with --defsym=NAME=ps5_NAME (ps5_getaddrinfo always returns EAI_FAIL); with --wrap
      that binding ended up on __wrap_getaddrinfo, so the stub won. Dropping the binding broke the link (the recipe's
      version script needs the symbol defined). Now the two names are bound to OUR functions instead
      (omni_inproc_getaddrinfo / omni_inproc_freeaddrinfo, same mechanism), and only fcntl is wrapped.

Patches the title's build.py (regenerated by prep_launch.py every build) AFTER apply_one_submitter.py build.
usage: apply_inproc_net_wraps.py <build.py> <src-title dir>"""
import sys
from pathlib import Path

MARK = 'OMNI_INPROC_NET_WRAPS_V1'
WRAPS = ['fcntl']
p, srcdir = Path(sys.argv[1]), Path(sys.argv[2])
src = srcdir / 'omni_inproc_net_wraps.c'
if not src.exists():
    sys.exit('missing %s' % src)
s = p.read_text(encoding='utf-8')
if MARK in s:
    print('already', p.name); sys.exit(0)


def rep(old, new):
    global s
    if s.count(old) != 1:
        sys.exit('%s: anchor found %d times (apply_one_submitter.py build first): %r' % (p.name, s.count(old), old[:70]))
    s = s.replace(old, new, 1)


# libSceNet (R2)
d = "libs = [secmap(l) if not l.startswith('-l') else l for l in libs]\n"
rep(d, d + "libs.append('-lSceNet')   # " + MARK + " R2: sceNetInit/Pool*/Resolver* for omni_inproc_getaddrinfo\n")

# getaddrinfo/freeaddrinfo bound to ours instead of the SDK stubs (R5)
e = "script, rinputs, rflags = [[x for x in part.split('\\0') if x] for part in r.stdout.split('\\1')]\n"
rep(e, e +
    "ONW_BIND = {'--defsym=getaddrinfo=ps5_getaddrinfo': '--defsym=getaddrinfo=omni_inproc_getaddrinfo',\n"
    "            '--defsym=freeaddrinfo=ps5_freeaddrinfo': '--defsym=freeaddrinfo=omni_inproc_freeaddrinfo'}   # " + MARK + " R5\n"
    "if not all(k in rflags for k in ONW_BIND): raise SystemExit('REFUSED: " + MARK + ": RADV recipe no longer binds getaddrinfo/freeaddrinfo to ps5_ (re-check R5)')\n"
    "rflags = [ONW_BIND.get(f, f) for f in rflags]\n")

# compile the file, next to the one-submitter object
a = "say('OMNI_GPU_ONE_SUBMITTER_V1: AGC driver calls go through one lock: ' + ', '.join(OGS_WRAPS))\n"
rep(a, a +
    "# " + MARK + ": fcntl wrap + getaddrinfo/freeaddrinfo for the in-process NetworkProcess (stage1/tools/apply_inproc_net_wraps.py)\n"
    f"ONW_SRC = Path({str(src)!r})\n"
    "o = B / 's1-omni_inproc_net_wraps.o'\n"
    "run([CC, '-std=gnu11', '-O2', '-Wall', '-Wextra', '-ffunction-sections', '-fdata-sections', '-D__PROSPERO__', '-c', ONW_SRC, '-o', o], out=B / 's1-omni_inproc_net_wraps.compile.log')\n"
    "mine.append(str(o))\n"
    f"ONW_WRAPS = {WRAPS!r}\n"
    "say('" + MARK + ": in-process network: wraps ' + ', '.join(ONW_WRAPS) + '; getaddrinfo/freeaddrinfo -> omni_inproc_*')\n")
b = "MY_WRAPS += OGS_WRAPS   # OMNI_GPU_ONE_SUBMITTER_V1\n"
rep(b, b + "MY_WRAPS += ONW_WRAPS   # " + MARK + "\n")

# gates on the linked title
c = "say('OMNI_GPU_ONE_SUBMITTER_V1 gate: __wrap_ defined for ' + ', '.join(OGS_WRAPS))\n"
rep(c, c +
    "onw_missing = [n for n in ONW_WRAPS if not re.search(rf' [tT] __wrap_{n}$', ogs_defs, re.M)]\n"
    "if onw_missing: raise SystemExit(f'REFUSED: " + MARK + " wraps missing from the title: {onw_missing}')\n"
    "for onw_fn in ('omni_inproc_getaddrinfo', 'omni_inproc_freeaddrinfo'):\n"
    "    if not re.search(rf' [tT] {onw_fn}$', ogs_defs, re.M): raise SystemExit(f'REFUSED: " + MARK + ": {onw_fn} missing from the title')\n"
    "say('" + MARK + " gate: __wrap_fcntl defined; getaddrinfo/freeaddrinfo bound to omni_inproc_* (Sony resolver)')\n")
p.write_text(s, encoding='utf-8')
print('applied', p.name)
