#!/usr/bin/env python3
"""omni-native-s0: generate src/import_check.cpp from the title's undefined dynamic symbols.

Same idea as Ex-Box's tools/audit_av2_native_imports.py: each import is declared weak under its
own name; at start-up its address is read (no call). A null address is an import the console did
not resolve, which would otherwise be a jump to address 0. Imports of lazily loaded modules
(libSceVideodec2: Omni loads it with sceSysmodule only when a video starts) are excluded here and
checked by dlsym() when they are first needed. Usage: gen_import_check.py SYMS.json OUT.cpp
SYMS.json = [[name, "FUNC"|"OBJECT"], ...]."""
import json, sys
syms = json.load(open(sys.argv[1]))
out = ["// Generated by omni-native-s0/tools/gen_import_check.py; do not hand-maintain.",
       "// Weak declarations allow observing an absent provider without invoking it.",
       "#include <unistd.h>"]
for i, (name, kind) in enumerate(syms):
    if kind == "OBJECT":
        out.append(f'extern "C" unsigned char omni_import_{i} asm("{name}") __attribute__((weak));')
    else:
        out.append(f'extern "C" void omni_import_{i}() asm("{name}") __attribute__((weak));')
out.append('extern "C" unsigned omni_native_check_imports(void (*log)(const char*, ...)) {')
out.append('  unsigned missing = 0;')
for i, (name, kind) in enumerate(syms):
    out.append(f'  {{ const void* volatile a = reinterpret_cast<const void*>(&omni_import_{i}); if (!a) {{ log("[import] missing {name}"); ++missing; }} }}')
out.append(f'  log("[import] checked={len(syms)} missing=%u", missing);')
out.append('  if (missing && access("/data/omni/native/import-check-continue.flag", F_OK) == 0) { log("[import] import-check-continue.flag: continuing anyway"); return 0; }')
out.append('  return missing;')
out.append('}')
open(sys.argv[2], 'w').write("\n".join(out) + "\n")
print(f"import check: {len(syms)} imports")
