#!/usr/bin/env python3
"""Embed unchanged, selected Kenney PNGs; optionally import the official archive."""
from pathlib import Path
import hashlib, html, json, shutil, sys
root=Path(__file__).resolve().parent
selection={}
for prefix,folder in [('xbox','Xbox Series'),('ps','PlayStation Series')]:
    names=(['xbox_button_'+b+'_outline.png' for b in 'abxy'] +
           ['xbox_lb_outline.png','xbox_rb_outline.png','xbox_button_view_outline.png',
            'xbox_button_menu_outline.png','xbox_stick_l.png','xbox_stick_r_press.png',
            'xbox_dpad_horizontal_outline.png']) if prefix=='xbox' else (
           ['playstation_button_'+b+'_outline.png' for b in ['cross','circle','square','triangle']] +
           ['playstation_trigger_l1_outline.png','playstation_trigger_r1_outline.png',
            'playstation5_button_create_outline.png','playstation5_button_options_outline.png',
            'playstation_stick_l.png','playstation_stick_r_press.png','playstation_dpad_horizontal_outline.png'])
    for key,name in zip(['a','b','x','y','lb','rb','view','menu','stick_l','stick_r_press','dpad_horizontal'],names):
        selection[prefix+'_'+key]=(folder,name)
if len(sys.argv)>1:
    archive=Path(sys.argv[1])
    for key,(folder,name) in selection.items():
        shutil.copyfile(archive/folder/'Double'/name,root/name)
    shutil.copyfile(archive/'License.txt',root/'LICENSE-KENNEY.txt')
parts=['// Generated by engine/resources/controller-icons/generate.py.\n',
       '// Unmodified Kenney Input Prompts 1.5A PNGs, CC0.\n',
       'namespace OmniControllerAssets {\n',
       'struct Image { const unsigned char* bytes; size_t size; };\n']
manifest=[]
for key,(folder,name) in selection.items():
    raw=(root/name).read_bytes()
    if raw[:8]!=b'\x89PNG\r\n\x1a\n': raise ValueError(name)
    parts.append(f'static const unsigned char {key}_png[] = {{\n')
    for offset in range(0,len(raw),20): parts.append(','.join(str(x) for x in raw[offset:offset+20])+',\n')
    parts.append('};\n')
    manifest.append({'id':key,'file':name,'archivePath':folder+'/Double/'+name,'sha256':hashlib.sha256(raw).hexdigest(),'bytes':len(raw)})
parts.append('enum Id { '+','.join(selection)+', Count };\n')
parts.append('static const Image images[] = {\n'+''.join('{'+key+'_png,sizeof('+key+'_png)},\n' for key in selection)+'};\n}\n')
(root/'OmniControllerAssets.h').write_text(''.join(parts))
(root/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
preview=['<!doctype html><meta charset="utf-8"><title>Omni controller prompts</title>',
         '<style>body{background:#111723;color:#e1e8f4;font:18px system-ui;padding:32px}section{display:flex;gap:24px;flex-wrap:wrap;margin:28px 0}figure{margin:0;text-align:center;width:110px}img{width:64px;height:64px;object-fit:contain}figcaption{font-size:13px}h1{color:#a8ef51}.bar{font-size:14px;display:flex;align-items:center;gap:8px;padding:18px 4px}.bar img{width:32px;height:32px}.gap{width:22px}</style>',
         '<h1>Omni · controller prompts</h1><p>Original Kenney Input Prompts 1.5A · CC0 · white outlines on the browser’s dark background.</p>']
for prefix,label in [('xbox','Xbox'),('ps','PlayStation')]:
    preview.append('<h2>'+label+'</h2><section>')
    for key,(folder,name) in selection.items():
        if key.startswith(prefix+'_'): preview.append('<figure><img src="'+html.escape(name)+'"><figcaption>'+html.escape(key)+'</figcaption></figure>')
    preview.append('</section><div class="bar">')
    for key,text in [('a','Click'),('y','Address'),('x','New tab'),('lb',''),('rb','Tabs'),('stick_r_press','Close tab'),('b','Back'),('view','Settings'),('menu','Exit')]:
        preview.append('<img src="'+selection[prefix+'_'+key][1]+'"><span>'+text+'</span><span class="gap"></span>')
    preview.append('</div>')
(root/'preview.html').write_text(''.join(preview))
print(f'Embedded {len(selection)} original PNGs ({sum(x["bytes"] for x in manifest)} bytes)')
