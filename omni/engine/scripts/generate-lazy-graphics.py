"""Generate typed forwarding functions from SDK headers; never emulate graphics.

Usage: generate-lazy-graphics.py SDK_INCLUDE EXISTING_ENGINE OUTPUT_CPP
The existing engine supplies the precise set of imported graphics functions.
"""
import pathlib
import re
import subprocess
import sys

headers, engine, output = map(pathlib.Path, sys.argv[1:])
symbols = subprocess.check_output(["nm", "-D", "--undefined-only", str(engine)], text=True)
needed = set(re.findall(r"\bU ((?:egl|gl[A-Z])\w*)", symbols))
if not needed:
    raise SystemExit("Input must be an engine that still imports graphics directly")
text = r'''// Generated by generate-lazy-graphics.py from the SDK's exact API declarations.
// Delay loading the real driver until an actual graphics API call is made.
#include <EGL/egl.h>
#include <GLES2/gl2.h>
#include <dlfcn.h>
#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>

static void* omniGraphicsSymbol(bool egl, const char* name)
{
    // Function-local initialization is thread-safe. No driver is loaded merely
    // because the UI or networking process starts.
    void* handle;
    if (egl) {
        static void* library = dlopen("/user/homebrew/lib/libEGL.so.1", RTLD_NOW | RTLD_LOCAL);
        handle = library;
    } else {
        static void* library = dlopen("/user/homebrew/lib/libGLESv2.so.2", RTLD_NOW | RTLD_LOCAL);
        handle = library;
    }
    void* symbol = handle ? dlsym(handle, name) : nullptr;
    if (!symbol) {
        fprintf(stderr, "Omni: cannot resolve real graphics function %s: %s\n", name, dlerror());
        fflush(stderr);
        fsync(fileno(stderr));
        abort();
    }
    return symbol;
}
'''
found = set()
for header in (headers / "EGL/egl.h", headers / "GLES2/gl2.h"):
    for result, name, arguments in re.findall(
        r"(?:EGLAPI|GL_APICALL)\s+(.+?)\s*(?:EGLAPIENTRY|GL_APIENTRY)\s+(\w+)\s*\(([^;]*?)\);",
        header.read_text(),
    ):
        if name not in needed:
            continue
        params = [] if arguments.strip() == "void" else arguments.split(",")
        names = [re.search(r"(\w+)\s*$", parameter).group(1) for parameter in params]
        text += f'\nextern "C" {result} {name}({arguments})\n{{\n'
        text += f'    static auto function = reinterpret_cast<decltype(&{name})>(omniGraphicsSymbol({str(name.startswith("egl")).lower()}, "{name}"));\n'
        text += f'    return function({", ".join(names)});\n}}\n'
        found.add(name)
if needed != found:
    raise SystemExit(f"Missing header declarations: {needed - found}")
output.write_text(text)
print(f"Generated {len(found)} typed forwarding functions")
