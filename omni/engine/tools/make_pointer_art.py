#!/usr/bin/env python3
"""OMNI_POINTER_STYLE_V1: build entry/OmniPointerArt.h from Kenney's CC0 Cursor Pack and Crosshair Pack.

Usage: make_pointer_art.py <cursor-pack dir> <crosshair-pack dir> <out OmniPointerArt.h>
Each style is rasterised from the pack's SVG at 384x384 into two 8-bit planes:
  fill = coverage of the light (body) parts, edge = coverage of the dark outline.
Cursors use the pack's "Outline" SVGs (white body, black outline): fill = a*L, edge = a*(1-L).
Crosshairs use the "Light" SVGs (white only); their edge plane is the body dilated by 6 px (at 384) minus the body.
The planes are zlib-compressed. Hotspots: nw = tip of a north-west arrow (min x+y of the drawn shape),
n = top of an upward finger (topmost row, its middle), c = centre of the drawn shape's bounding box.
Source and licence (CC0 1.0) are written into the header."""
import sys, zlib, io
import cairosvg
from PIL import Image, ImageFilter
import numpy as np

S = 384
CURSORS = [  # (shown name, file, hotspot rule)
    ("Arrow", "pointer_c", "nw"),
    ("Arrow, classic", "pointer_a", "nw"),
    ("Arrow, rounded", "pointer_d", "nw"),
    ("Arrow, cartoon", "pointer_toon_a", "nw"),
    ("Arrow, sci-fi", "pointer_scifi_a", "nw"),
    ("Dart", "navigation_nw", "nw"),
    ("Arrow, line", "pointer_g", "nw"),
    ("Hand", "hand_point", "n"),
    ("Hand, slim", "hand_thin_point", "n"),
    ("Gauntlet", "gauntlet_point", "nw"),
    ("Dot", "dot_large", "c"),
    ("Ring target", "target_round_b", "c"),
    ("Cross, gap", "target_a", "c"),
]
CROSSHAIRS = [
    ("Crosshair, small plus", 1), ("Crosshair, dotted", 16), ("Crosshair, open", 20),
    ("Crosshair, scope", 8), ("Crosshair, bullseye", 9), ("Crosshair, ticks", 26),
    ("Crosshair, ring dot", 87), ("Crosshair, box", 104), ("Crosshair, small ring", 169),
    ("Crosshair, sight", 175), ("Crosshair, diamond", 18),
]

def render(svg_path):
    png = cairosvg.svg2png(url=svg_path, output_width=S, output_height=S)
    im = Image.open(io.BytesIO(png)).convert("RGBA")
    a = np.asarray(im).astype(np.float32) / 255.0
    return a[..., :3], a[..., 3]

def hotspot(alpha, rule):
    ys, xs = np.nonzero(alpha > 0.5)
    if rule == "nw":
        k = np.argmin(xs + ys); return int(xs[k]), int(ys[k])
    if rule == "n":
        y0 = ys.min(); row = xs[ys == y0]; return int(round(row.mean())), int(y0)
    return int(round((xs.min() + xs.max()) / 2)), int(round((ys.min() + ys.max()) / 2))

def emit(out, styles, cursor_dir, cross_dir):
    lines = ["// OMNI_POINTER_STYLE_V1: generated by tools/make_pointer_art.py; do not edit.",
             "// Pointer art: Kenney (www.kenney.nl), \"Cursor Pack\" 1.1 and \"Crosshair Pack\" 1.1,",
             "// licence Creative Commons Zero (CC0 1.0), http://creativecommons.org/publicdomain/zero/1.0/",
             "// Each entry: SxS fill plane then SxS edge plane (8-bit coverage, S = omniPointerArtSize), zlib-compressed.",
             "#pragma once", "#include <cstdint>", f"constexpr int omniPointerArtSize = {S};",
             "struct OmniPointerArt { const char* name; uint8_t crosshair; uint16_t hotX, hotY; uint32_t zlen; const uint8_t* z; };"]
    table = []
    for i, (name, kind, path, rule) in enumerate(styles):
        rgb, a = render(path)
        lum = (0.2126 * rgb[..., 0] + 0.7152 * rgb[..., 1] + 0.0722 * rgb[..., 2])
        if kind == 0:
            fill, edge = a * lum, a * (1 - lum)
        else:
            body = Image.fromarray((a * 255).astype(np.uint8))
            dil = np.asarray(body.filter(ImageFilter.MaxFilter(13))).astype(np.float32) / 255.0
            dil = np.asarray(Image.fromarray((dil * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(0.8))).astype(np.float32) / 255.0
            fill, edge = a, np.clip(dil - a, 0, 1)
        hx, hy = hotspot(np.maximum(fill, edge), rule)
        raw = np.concatenate([(fill * 255 + 0.5).astype(np.uint8).ravel(), (edge * 255 + 0.5).astype(np.uint8).ravel()]).tobytes()
        z = zlib.compress(raw, 9)
        body = ",".join(str(b) for b in z)
        lines.append(f"static const uint8_t omniPointerArt{i}[{len(z)}] = {{{body}}};")
        table.append(f'    {{ "{name}", {kind}, {hx}, {hy}, {len(z)}u, omniPointerArt{i} }},')
        print(f"{i:2d} {name:28s} kind={kind} hot=({hx},{hy}) z={len(z)}", file=sys.stderr)
    lines.append("static const OmniPointerArt omniPointerArts[] = {")
    lines += table
    lines.append("};")
    lines.append("constexpr int omniPointerArtCount = int(sizeof(omniPointerArts) / sizeof(omniPointerArts[0]));")
    open(out, "w", newline="\r\n").write("\n".join(lines) + "\n")

if __name__ == "__main__":
    cu, ch, out = sys.argv[1:4]
    styles = [(n, 0, f"{cu}/Vector/Outline/{f}.svg", r) for n, f, r in CURSORS]
    styles += [(n, 1, f"{ch}/Vector/Light/crosshair-{k:03d}.svg", "c") for n, k in CROSSHAIRS]
    emit(out, styles, cu, ch)
